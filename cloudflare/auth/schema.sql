CREATE TABLE IF NOT EXISTS dm_threads(id TEXT PRIMARY KEY,a TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,b TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,initiator TEXT NOT NULL,status TEXT NOT NULL DEFAULT 'pending',kind TEXT NOT NULL DEFAULT 'normal',updated_at INTEGER NOT NULL,UNIQUE(a,b,kind));
CREATE TABLE IF NOT EXISTS dm_messages(id TEXT PRIMARY KEY,thread_id TEXT NOT NULL REFERENCES dm_threads(id) ON DELETE CASCADE,sender TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,body TEXT NOT NULL,created_at INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS dm_messages_thread ON dm_messages(thread_id,created_at);
CREATE TABLE IF NOT EXISTS dm_reports(id TEXT PRIMARY KEY,thread_id TEXT NOT NULL,message_id TEXT,reporter TEXT NOT NULL,reason TEXT NOT NULL,created_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS dm_profiles(user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,nickname TEXT NOT NULL,updated_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS dm_rooms(id TEXT PRIMARY KEY,name TEXT NOT NULL,visibility TEXT NOT NULL,owner TEXT NOT NULL,created_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS dm_members(room_id TEXT NOT NULL REFERENCES dm_rooms(id) ON DELETE CASCADE,user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,status TEXT NOT NULL,PRIMARY KEY(room_id,user_id));
CREATE TABLE IF NOT EXISTS dm_room_messages(id TEXT PRIMARY KEY,room_id TEXT NOT NULL REFERENCES dm_rooms(id) ON DELETE CASCADE,sender TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,body TEXT NOT NULL,created_at INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS dm_room_messages_page ON dm_room_messages(room_id,created_at);
CREATE TABLE IF NOT EXISTS dm_room_reports(id TEXT PRIMARY KEY,room_id TEXT NOT NULL,message_id TEXT NOT NULL,reporter TEXT NOT NULL,reason TEXT NOT NULL,created_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS client_releases(channel TEXT PRIMARY KEY,version TEXT NOT NULL,manifest TEXT NOT NULL,published_at INTEGER NOT NULL,checked_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS device_releases(user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,device_id TEXT NOT NULL,version TEXT NOT NULL,applied_at INTEGER NOT NULL,last_seen INTEGER NOT NULL,last_error TEXT NOT NULL DEFAULT '',PRIMARY KEY(user_id,device_id));
CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  password_salt TEXT NOT NULL,
  created_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires_at);
CREATE TABLE IF NOT EXISTS history (
  user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  data TEXT NOT NULL DEFAULT '[]',
  version INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS login_attempts (
  key TEXT PRIMARY KEY,
  count INTEGER NOT NULL,
  window_start INTEGER NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS users_username_nocase ON users(LOWER(username));
CREATE TABLE IF NOT EXISTS account_visual_modes (
  user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  mode TEXT NOT NULL DEFAULT 'off' CHECK (mode IN ('off','chaos','chaos2','jelly')),
  updated_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS account_controls (
  user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  banned INTEGER NOT NULL DEFAULT 0,
  traffic_stopped INTEGER NOT NULL DEFAULT 0,
  updated_at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS account_usage (
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  day TEXT NOT NULL,
  requests INTEGER NOT NULL DEFAULT 0,
  videos INTEGER NOT NULL DEFAULT 0,
  searches INTEGER NOT NULL DEFAULT 0,
  last_seen INTEGER NOT NULL,
  PRIMARY KEY (user_id, day)
);
CREATE TABLE IF NOT EXISTS api_oauth_flows (user_id TEXT PRIMARY KEY, data TEXT NOT NULL, expires_at INTEGER NOT NULL);
